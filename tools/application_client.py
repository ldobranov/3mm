"""Generate a local, one-dispatch TypeScript client from validated declarations."""
from __future__ import annotations

import hashlib
import json
import math
import os
from pathlib import Path
import re
import stat
import tempfile

from three_mm_protocol.application_extension import ApplicationExtensionV1
from tools import application_project
from tools.application_project import ProjectCheckError

MARKER = '// Generated by 3mm application client v1; do not edit.'
UI_AUDIENCES = frozenset({'public', 'kiosk', 'operator', 'administrator'})
_ANNOTATIONS = {'title', 'description', 'default', 'examples', '$comment', 'readOnly', 'writeOnly', 'deprecated'}
_SCALARS = {'string', 'integer', 'number', 'boolean', 'null'}


def _fail(message):
    raise ProjectCheckError('client', message)


def _literal(value):
    return json.dumps(value, ensure_ascii=True, allow_nan=False, separators=(',', ':'))


def _schema_type(schema, *, budget, depth=0):
    budget[0] += 1
    if depth > 12 or budget[0] > 2048 or type(schema) is not dict:
        _fail('Client schemas exceed the supported bounded object/array/scalar profile.')
    kinds = schema.get('type')
    nullable = isinstance(kinds, list)
    if nullable:
        if (len(kinds) != 2 or any(type(kind) is not str for kind in kinds)
                or len(set(kinds)) != 2 or 'null' not in kinds):
            _fail('Only a declared type plus null is supported as a schema type union.')
        kind = next(kind for kind in kinds if kind != 'null')
    else:
        kind = kinds
    if not isinstance(kind, str):
        _fail('Client schemas need one explicit supported JSON type.')
    common = _ANNOTATIONS | {'type', 'enum'}
    allowed = (common | {'properties', 'required', 'additionalProperties', 'minProperties', 'maxProperties'} if kind == 'object' else
               common | {'items', 'minItems', 'maxItems', 'uniqueItems'} if kind == 'array' else
               common | {'minLength', 'maxLength', 'pattern', 'format'} if kind == 'string' else
               common | {'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf'} if kind in {'integer', 'number'} else common)
    if kind not in _SCALARS | {'object', 'array'} or set(schema) - allowed:
        _fail('Unsupported schema keywords/type: references and combinators are not widened into any.')

    if 'enum' in schema:
        values = schema['enum']
        if kind not in _SCALARS or type(values) is not list or not 1 <= len(values) <= 128:
            _fail('Client enums must be bounded primitive values with an explicit scalar type.')
        for value in values:
            valid = (value is None and (nullable or kind == 'null')
                or kind == 'string' and type(value) is str
                or kind == 'boolean' and type(value) is bool
                or kind == 'integer' and type(value) is int and abs(value) <= 2**53-1
                or kind == 'number' and (type(value) is int and abs(value) <= 2**53-1
                    or type(value) is float and math.isfinite(value)))
            if not valid:
                _fail('Client enum values do not match the declared JSON type or safe numeric literal range.')
        return ' | '.join(sorted({_literal(value) for value in values}))

    if kind == 'object':
        properties, required = schema.get('properties', {}), schema.get('required', [])
        if (type(properties) is not dict or type(required) is not list
                or any(type(name) is not str for name in properties)
                or any(type(name) is not str for name in required)
                or len(set(required)) != len(required) or set(required) - set(properties)):
            _fail('Client object properties/required declarations are invalid.')
        fields = ['readonly ' + _literal(name) + ('' if name in required else '?') + ': '
                  + _schema_type(value, budget=budget, depth=depth+1) for name, value in sorted(properties.items())]
        declared = '{ ' + '; '.join(fields) + ' }'
        additional = schema.get('additionalProperties', True)
        if additional is False:
            rendered = declared if fields else 'Record<string, never>'
        elif additional is True:
            rendered = f'({declared} & Record<string, ApplicationJson>)' if fields else 'Record<string, ApplicationJson>'
        elif type(additional) is dict and not properties:
            rendered = 'Record<string, ' + _schema_type(additional, budget=budget, depth=depth+1) + '>'
        else:
            _fail('Typed additional properties mixed with named fields cannot be represented faithfully by this client profile.')
    elif kind == 'array':
        item = _schema_type(schema['items'], budget=budget, depth=depth+1) if 'items' in schema else 'ApplicationJson'
        rendered = 'Array<' + item + '>'
    else:
        rendered = {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}[kind]
    return '(' + rendered + ' | null)' if nullable else rendered


def _operations(definition):
    if not isinstance(definition, ApplicationExtensionV1):
        _fail('A validated ApplicationExtensionV1 definition is required.')
    operations = sorted((operation for operation in definition.operations if UI_AUDIENCES & set(operation.audiences)),
                        key=lambda operation: operation.operation_id)
    if not operations:
        _fail('The application declares no UI-audience operations for a generated client.')
    if any(operation.kind not in {'query', 'command'} or operation.idempotency !=
           ('required' if operation.kind == 'command' else 'forbidden') for operation in operations):
        _fail('UI client operations must use the current query/command idempotency contract.')
    return operations


def contract_digest(definition):
    operations = _operations(definition)
    declaration = {'module_id': definition.module_id, 'version': definition.version,
        'application_extension_version': definition.application_extension_version,
        'sdk_version': definition.service.sdk_version,
        'operations': [operation.model_dump(mode='json') for operation in operations]}
    canonical = json.dumps(declaration, sort_keys=True, ensure_ascii=True, allow_nan=False, separators=(',', ':'))
    return hashlib.sha256(canonical.encode()).hexdigest()


def render_client(definition) -> str:
    """Render types, not a new validator, transport or permission authority."""
    operations, aliases, declarations, methods = _operations(definition), set(), [], []
    for operation in operations:
        alias = ''.join(part.capitalize() for part in operation.operation_id.split('_'))
        if alias in aliases:
            _fail('Operation IDs collide as generated TypeScript names; choose distinct declaration names.')
        aliases.add(alias)
        budget = [0]
        input_type = _schema_type(operation.input_schema, budget=budget)
        output_type = _schema_type(operation.output_schema, budget=budget)
        declarations += [f'export type {alias}Input = {input_type}', f'export type {alias}Output = {output_type}', '']
        options = ", options: { readonly idempotencyKey: string }" if operation.kind == 'command' else ''
        arguments = ', { idempotencyKey: options.idempotencyKey }' if options else ''
        methods += [f'    {_literal(operation.operation_id)}(payload: {alias}Input{options}): Promise<{alias}Output> {{',
                    f'      return host.invoke({_literal(operation.operation_id)}, payload{arguments}) as Promise<{alias}Output>', '    },']
    digest = contract_digest(definition)
    imports = 'ApplicationHost' + (', ApplicationJson' if any('ApplicationJson' in line for line in declarations) else '')
    body = '\n'.join([
        '// Compile-time structural types only. Runtime validation remains authoritative for bounds,',
        '// integerness, patterns, counts and exact JSON values. No code trust or access is granted.',
        '// Commands require the original caller-owned key. One invoke, no retry or generated IDs.',
        f"import type {{ {imports} }} from '@3mm/application-ui/v1'", '',
        f'export const APPLICATION_CLIENT_CONTRACT_SHA256 = {_literal(digest)} as const', '',
        *declarations, "export function createApplicationClient(host: Pick<ApplicationHost, 'invoke'>) {", '  return {',
        *methods, '  }', '}', ''])
    header = '\n'.join([MARKER, '// Module: ' + definition.module_id, '// Contract SHA256: ' + digest,
        '// Body SHA256: ' + hashlib.sha256(body.encode('utf-8')).hexdigest(), '', ''])
    result = header + body
    if len(result.encode('utf-8')) > 1024 * 1024:
        _fail('Generated client exceeds the local source-file budget.')
    return result


def _owned(data, module_id):
    normalized = data.replace(b'\r\n', b'\n')
    try:
        header, body = normalized.split(b'\n\n', 1)
        lines = header.decode('utf-8').splitlines()
        return (len(lines) == 4 and lines[0] == MARKER and lines[1] == '// Module: ' + module_id
            and re.fullmatch('// Contract SHA256: [0-9a-f]{64}', lines[2]) is not None
            and lines[3] == '// Body SHA256: ' + hashlib.sha256(body).hexdigest())
    except (UnicodeError, ValueError):
        return False


def _target(project, output):
    raw = Path(output)
    if '..' in raw.parts or raw.drive and not raw.is_absolute():
        _fail('Client output must be a project-local source/frontend/*.ts path.')
    target = Path(os.path.abspath(raw if raw.is_absolute() else project / raw))
    try:
        relative = target.relative_to(project)
    except ValueError:
        _fail('Client output must remain inside this project source/frontend directory.')
    if relative.parts[:2] != ('source', 'frontend') or len(relative.parts) < 3 or target.suffix != '.ts' or target.name.endswith('.d.ts'):
        _fail('Client output must be an implementation .ts file under source/frontend.')
    if any(path.is_symlink() or getattr(path, 'is_junction', lambda: False)() for path in (target, *target.parents)):
        _fail('Client output and parents must not use symbolic links or junctions.')
    if not target.parent.is_dir():
        _fail('Client output parent must already be an application source directory.')
    return target, relative.as_posix()


def _replace_recoverably(project, target, staged, old):
    """Displace, inspect, then publish exclusively; never overwrite a racer.

    Explicit regeneration may briefly leave the target absent. Always retain
    the displaced inode: an editor could still hold it open and write to it.
    """
    parent = project
    for name in ('.runtime', 'client-recovery'):
        parent = parent / name
        if not os.path.lexists(parent):
            try:
                parent.mkdir()
            except FileExistsError:
                pass
        if (parent.is_symlink() or getattr(parent, 'is_junction', lambda: False)()
                or not parent.is_dir()):
            _fail('Client recovery directories must be regular project-local directories, not redirects.')
    owned = Path(tempfile.mkdtemp(prefix='previous-', dir=parent))
    backup = owned / 'client.ts.bak'
    recovery = backup.relative_to(project).as_posix()
    try:
        os.rename(target, backup)
        if not stat.S_ISREG(backup.lstat().st_mode) or backup.read_bytes() != old:
            _fail('Client source changed at the replacement boundary.')
        os.link(staged, target)
    except BaseException as failure:
        if os.path.lexists(backup):
            try:
                os.link(backup, target, follow_symlinks=False)
            except (OSError, NotImplementedError):
                pass  # A competing target stays untouched; displaced bytes remain.
            raise ProjectCheckError('client', 'Replacement was not confirmed. Displaced source is retained at '
                                    + recovery + '; inspect it and the current output before another action.') from failure
        raise ProjectCheckError('client', 'Replacement did not complete; the current output was not overwritten.') from failure
    return recovery


def generate_client(project: Path, output: Path, *, replace: bool = False) -> dict:
    """Publish new source explicitly; never run app code/checks or overwrite edits."""
    from backend.services.module_packages import validate_module_package

    project = Path(os.path.abspath(project))
    if project.is_symlink() or not project.is_dir():
        _fail('Select a regular application source project.')
    target, relative = _target(project, output)
    recovery = None
    try:
        if os.path.lexists(target) and not stat.S_ISREG(target.lstat().st_mode):
            _fail('Client output is not a regular file.')
        old = target.read_bytes() if os.path.lexists(target) else None
        source = application_project.inputs(project)
        if old is not None and source.get(relative) != old.replace(b'\r\n', b'\n'):
            _fail('Client output changed while source was being captured; nothing was written.')
        source_hash = application_project.fingerprint(source)
        with tempfile.TemporaryDirectory(prefix='3mm-application-client-') as temporary:
            snapshot = Path(temporary)
            for name, data in source.items():
                path = snapshot / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            validated = validate_module_package(application_project.build_package(snapshot))
            definition = validated.application_extension
            if definition is None:
                _fail('Client generation requires a current application package.')
            rendered = render_client(definition).encode('utf-8')
            (snapshot / relative).parent.mkdir(parents=True, exist_ok=True)
            (snapshot / relative).write_bytes(rendered)
            application_project.inputs(snapshot)  # Reuse current source size/count guards.
            if application_project.fingerprint(application_project.inputs(project)) != source_hash:
                _fail('Application source changed during client generation; nothing was written.')
            if old is not None and old.replace(b'\r\n', b'\n') == rendered:
                _target(project, output)
                if not target.is_file() or target.read_bytes() != old:
                    _fail('Client output changed during generation; unchanged output was not confirmed.')
                status = 'unchanged'
            else:
                if old is not None and (not replace or not _owned(old, definition.module_id)):
                    _fail('Output exists: only an unedited generated client for this module can be explicitly replaced.')
                with tempfile.NamedTemporaryFile(prefix='.3mm-client-', suffix='.tmp', dir=target.parent, delete=False) as staged:
                    owned = Path(staged.name)
                    staged.write(rendered)
                    staged.flush()
                    os.fsync(staged.fileno())
                try:
                    _target(project, output)
                    if old is None:
                        os.link(owned, target)  # Exclusive publication; never clobber a racing file.
                        status = 'created'
                    else:
                        if not target.is_file() or target.read_bytes() != old:
                            _fail('Client output changed during generation; nothing was replaced.')
                        recovery = _replace_recoverably(project, target, owned, old)
                        status = 'replaced'
                finally:
                    owned.unlink(missing_ok=True)
        _target(project, output)
        confirmed = target.read_bytes()
        if confirmed.replace(b'\r\n', b'\n') != rendered:
            _fail('Generated output is no longer confirmed; inspect the current file before another action.')
        result = {'status': status, 'output': relative, 'module_id': definition.module_id,
            'contract_sha256': contract_digest(definition), 'sha256': hashlib.sha256(confirmed).hexdigest(),
            'operations': [operation.operation_id for operation in _operations(definition)],
            'checks': 'not_run', 'installation': 'not_requested', 'grants': 'not_requested'}
        if recovery is not None:
            result['recovery_file'] = recovery
        return result
    except ProjectCheckError as failure:
        if recovery is not None:
            raise ProjectCheckError('client', str(failure) + ' Displaced source is retained at ' + recovery + '.') from failure
        raise
    except (OSError, ValueError, KeyError, TypeError, SyntaxError) as failure:
        hint = ' Displaced source is retained at ' + recovery + '.' if recovery is not None else ''
        raise ProjectCheckError('client', 'Client generation did not complete; inspect current source/output before another action.' + hint) from failure
