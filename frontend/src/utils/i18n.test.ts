import { beforeEach, describe, expect, it, vi } from 'vitest'
const api = vi.hoisted(() => ({ available: vi.fn(), translations: vi.fn(), save: vi.fn() }))
vi.mock('@/utils/language-api', () => ({ readAvailableLanguages: api.available, readFrontendTranslations: api.translations, saveCurrentUserLanguage: api.save }))
beforeEach(() => { vi.resetModules(); vi.clearAllMocks(); localStorage.clear(); api.available.mockResolvedValue(['en','de']); api.translations.mockResolvedValue({ custom: { title: 'First package' } }); api.save.mockResolvedValue(undefined) })
describe('current language extension data', () => {
  it('discovers generic installed languages without importing a bundled locale', async () => {
    const { i18n, initializeI18n } = await import('./i18n')
    localStorage.setItem('preferredLanguage','de')
    await initializeI18n()
    expect(i18n.getAvailableLanguages()).toEqual(['en','de'])
    expect(i18n.t('custom.title')).toBe('First package')
    expect(api.translations).toHaveBeenCalledWith('de')
  })
  it('replaces old keys on a package change and returns to English after disable', async () => {
    const { i18n } = await import('./i18n')
    await i18n.refreshLanguages(); await i18n.setLanguage('de',false)
    api.translations.mockResolvedValue({ replacement: { title: 'Replacement' } })
    await i18n.refreshLanguages()
    expect(i18n.t('custom.title')).toBe('custom.title')
    expect(i18n.t('replacement.title')).toBe('Replacement')
    api.available.mockResolvedValue(['en'])
    await i18n.refreshLanguages()
    expect(i18n.getCurrentLanguage()).toBe('en')
    expect(i18n.t('replacement.title')).toBe('replacement.title')
    expect(api.save).not.toHaveBeenCalled()
  })
  it('starts the English administration if optional language discovery fails', async () => {
    api.available.mockRejectedValue(new Error('unavailable'))
    const { i18n, initializeI18n } = await import('./i18n')
    localStorage.setItem('preferredLanguage','de')
    await initializeI18n()
    expect(i18n.getCurrentLanguage()).toBe('en')
    expect(i18n.getAvailableLanguages()).toEqual(['en'])
  })
})
